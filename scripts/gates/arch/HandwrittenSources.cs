using System.Diagnostics;
using System.Text.Json;

namespace Campus.Arch.Tests;

// Supplies the shared handwritten-source boundary to source-based policy checks.
internal static class HandwrittenSources
{
    internal static IEnumerable<string> Paths(string root)
    {
        using var thirdParty = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "third_party.json")));
        var external = thirdParty.RootElement.GetProperty("entries").EnumerateArray()
            .Where(entry => entry.TryGetProperty("path", out _))
            .Select(entry => entry.GetProperty("path").GetString()!.Replace('\\', '/').TrimEnd('/')).ToArray();
        var paths = Run(root, "git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"])
            .Split('\0', StringSplitOptions.RemoveEmptyEntries).Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(path => path, StringComparer.Ordinal);
        foreach (var path in paths)
        {
            if (!IsSource(path) || !File.Exists(Path.Combine(root, path))) continue;
            if (external.Any(prefix => path.Equals(prefix, StringComparison.OrdinalIgnoreCase) ||
                path.StartsWith(prefix + "/", StringComparison.OrdinalIgnoreCase))) continue;
            var text = File.ReadAllText(Path.Combine(root, path));
            if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) ||
                text.StartsWith("// Generated by scripts/build/generate-style-shaders.py", StringComparison.Ordinal)) continue;
            yield return path;
        }
    }

    private static bool IsSource(string path) => Path.GetExtension(path).ToLowerInvariant() is
        ".cs" or ".gdshader" or ".gdshaderinc" or ".glsl" or ".glslinc" or ".py" or
        ".ps1" or ".psm1" or ".js" or ".mjs" or ".cjs" or ".jsx" or ".ts" or ".tsx" or
        ".cmd" or ".bat" or ".sh" or ".gd";

    private static string Run(string root, string executable, string[] arguments)
    {
        var info = new ProcessStartInfo(executable)
        {
            WorkingDirectory = root, RedirectStandardOutput = true, RedirectStandardError = true,
            UseShellExecute = false, CreateNoWindow = true
        };
        foreach (var argument in arguments) info.ArgumentList.Add(argument);
        using var process = Process.Start(info) ?? throw new InvalidOperationException("Could not start source listing: " + executable);
        var errors = process.StandardError.ReadToEndAsync();
        var output = process.StandardOutput.ReadToEnd();
        process.WaitForExit();
        var error = errors.GetAwaiter().GetResult();
        if (process.ExitCode != 0) throw new InvalidOperationException($"Source listing failed ({executable}): {error}\n{output}");
        return output;
    }
}
