using System.Diagnostics;
using System.Text.Json;
using System.Text.RegularExpressions;
using GdUnit4;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Campus.Arch.Tests;

[TestSuite]
public sealed class SourcePolicyGateTests
{
    private static readonly string[] Terms =
        ["fallback", "legacy", "compat", "workaround", "hack", "shim", "temporary", "兜底", "绕过", "临时方案", "先凑合"];

    [TestCase]
    [TestCategory("Contract")]
    public void HandwrittenDeclarationsAndCommentsUseResponsibilityNames()
    {
        var root = Environment.GetEnvironmentVariable("UESTC_REPOSITORY") ?? ArchitectureTests.FindRepository();
        var files = HandwrittenPaths(root).ToArray();
        var errors = new List<string>();
        foreach (var path in files.Where(path => path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)))
            InspectCSharp(root, path, errors);
        foreach (var path in files.Where(IsShader)) InspectShader(root, path, errors);
        var scripts = files.Where(path => !path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) && !IsShader(path)).ToArray();
        var output = Run(root, "python", ["-I", "-X", "utf8", "scripts/gates/arch/source-policy.py"],
            JsonSerializer.Serialize(new { root, files = scripts, terms = Terms }));
        errors.AddRange(JsonSerializer.Deserialize<string[]>(output)
            ?? throw new InvalidOperationException("G4 source policy returned no result."));
        SourceModel.RequireNoViolations(errors);
    }

    internal static IEnumerable<string> HandwrittenPaths(string root)
    {
        using var thirdParty = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "third_party.json")));
        var external = thirdParty.RootElement.GetProperty("entries").EnumerateArray()
            .Where(entry => entry.TryGetProperty("path", out _))
            .Select(entry => entry.GetProperty("path").GetString()!.Replace('\\', '/').TrimEnd('/')).ToArray();
        var paths = Run(root, "git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"])
            .Split('\0', StringSplitOptions.RemoveEmptyEntries).Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(path => path, StringComparer.Ordinal);
        foreach (var path in paths)
        {
            if (!IsSource(path) || !File.Exists(Path.Combine(root, path))) continue;
            if (external.Any(prefix => path.Equals(prefix, StringComparison.OrdinalIgnoreCase) ||
                path.StartsWith(prefix + "/", StringComparison.OrdinalIgnoreCase))) continue;
            var text = File.ReadAllText(Path.Combine(root, path));
            if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) ||
                text.StartsWith("// Generated by scripts/build/generate-style-shaders.py", StringComparison.Ordinal)) continue;
            yield return path;
        }
    }

    private static bool IsSource(string path) => Path.GetExtension(path).ToLowerInvariant() is
        ".cs" or ".gdshader" or ".gdshaderinc" or ".glsl" or ".glslinc" or ".py" or
        ".ps1" or ".psm1" or ".js" or ".mjs" or ".cjs" or ".jsx" or ".ts" or ".tsx" or
        ".cmd" or ".bat" or ".sh" or ".gd";

    private static bool IsShader(string path) => Path.GetExtension(path).ToLowerInvariant() is
        ".gdshader" or ".gdshaderinc" or ".glsl" or ".glslinc";

    private static void InspectShader(string root, string path, List<string> errors)
    {
        var text = File.ReadAllText(Path.Combine(root, path));
        var directives = Regex.Matches(text, @"(?m)^[ \t]*#[^\r\n]*");
        var bodyStarts = new Dictionary<int, int>();
        foreach (Match directive in directives)
        {
            var define = Regex.Match(directive.Value, @"^[ \t]*#[ \t]*define[ \t]+([\p{L}_][\p{L}\p{N}_]*)(\([^)]*\))?");
            bodyStarts.Add(directive.Index, define.Success ? directive.Index + define.Length : directive.Index + directive.Length);
            if (!define.Success) continue;
            var line = text.AsSpan(0, directive.Index).Count('\n') + 1;
            Inspect(path, line, "declaration", define.Groups[1].Value, errors);
            foreach (Match parameter in Regex.Matches(define.Groups[2].Value, @"[\p{L}_][\p{L}\p{N}_]*"))
                Inspect(path, line, "declaration", parameter.Value, errors);
        }
        // Remove directive markers before lexing so no preprocessor branch becomes disabled text.
        var input = Regex.Replace(text, @"(?m)^([ \t]*)#", "$1 ");
        var tokens = SyntaxFactory.ParseTokens(input, options: CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview)).ToArray();
        foreach (var trivia in tokens.SelectMany(token => token.LeadingTrivia.Concat(token.TrailingTrivia)))
            if (trivia.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia or
                SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia)
                Inspect(path, text.AsSpan(0, trivia.SpanStart).Count('\n') + 1, "comment", trivia.ToFullString(), errors);
        var code = tokens.Where(token => !directives.Cast<Match>().Any(directive => token.SpanStart >= directive.Index &&
            token.SpanStart < bodyStarts[directive.Index])).ToArray();
        InspectShaderDeclarations(path, text, code, errors);
    }

    private static void InspectShaderDeclarations(string path, string text, SyntaxToken[] tokens, List<string> errors)
    {
        var depth = 0;
        int? declarationDepth = null;
        var uniformDeclaration = false;
        for (var index = 0; index < tokens.Length; index++)
        {
            var token = tokens[index];
            if (token.Text is "(" or "[" or "{") depth++;
            if (token.Text is ")" or "]" or "}") { depth--; if (declarationDepth > depth) declarationDepth = null; }
            if (token.Text == "uniform") uniformDeclaration = true;
            if (token.Text == ";") { declarationDepth = null; uniformDeclaration = false; }
            if (token.Text == ":" && uniformDeclaration) declarationDepth = null;
            if (!token.IsKind(SyntaxKind.IdentifierToken) || index == 0) continue;
            var previous = tokens[index - 1];
            var typed = IsShaderType(previous) && (index < 2 || tokens[index - 2].Text != ".");
            var continued = previous.Text == "," && declarationDepth == depth;
            if (!typed && !continued && previous.Text != "struct") continue;
            Inspect(path, text.AsSpan(0, token.SpanStart).Count('\n') + 1, "declaration", token.ValueText, errors);
            declarationDepth = index + 1 < tokens.Length && tokens[index + 1].Text == "(" ? null : depth;
        }
    }

    private static bool IsShaderType(SyntaxToken token) => token.Kind() is SyntaxKind.FloatKeyword or SyntaxKind.DoubleKeyword or
        SyntaxKind.IntKeyword or SyntaxKind.UIntKeyword or SyntaxKind.BoolKeyword or SyntaxKind.VoidKeyword ||
        token.IsKind(SyntaxKind.IdentifierToken) && token.ValueText is not
            ("shader_type" or "render_mode" or "group_uniforms" or "uniform" or "global" or "instance" or
             "in" or "out" or "inout" or "lowp" or "mediump" or "highp" or "readonly" or "writeonly" or
             "coherent" or "restrict" or "volatile" or "buffer" or "shared" or "precision" or "layout");

    private static void InspectCSharp(string root, string path, List<string> errors)
    {
        var options = CSharpParseOptions.Default.WithLanguageVersion(LanguageVersion.Preview)
            .WithPreprocessorSymbols("DEBUG", "TRACE", "GODOT", "GODOT4", "TOOLS");
        var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(Path.Combine(root, path)), options, path);
        var syntax = tree.GetRoot();
        if (syntax.GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)) return;
        InspectCSharpTree(path, tree, syntax, 0, errors);
    }

    private static void InspectCSharpTree(string path, SyntaxTree tree, SyntaxNode syntax, int lineOffset, List<string> errors)
    {
        foreach (var node in syntax.DescendantNodes(descendIntoTrivia: true))
        foreach (var name in DeclaredNames(node))
            Inspect(path, lineOffset + tree.GetLineSpan(name.Span).StartLinePosition.Line + 1, "declaration", name.ValueText, errors);
        foreach (var trivia in syntax.DescendantTrivia(descendIntoTrivia: true))
        {
            var line = lineOffset + tree.GetLineSpan(trivia.Span).StartLinePosition.Line + 1;
            if (trivia.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia or
                SyntaxKind.SingleLineDocumentationCommentTrivia or SyntaxKind.MultiLineDocumentationCommentTrivia)
                Inspect(path, line, "comment", trivia.ToFullString(), errors);
            if (trivia.IsKind(SyntaxKind.DisabledTextTrivia))
            {
                var branch = CSharpSyntaxTree.ParseText(trivia.ToFullString(), (CSharpParseOptions)tree.Options);
                InspectCSharpTree(path, branch, branch.GetRoot(), line - 1, errors);
            }
        }
    }

    private static IEnumerable<SyntaxToken> DeclaredNames(SyntaxNode node)
    {
        var identifier = node switch
        {
            BaseTypeDeclarationSyntax declaration => declaration.Identifier,
            DelegateDeclarationSyntax declaration => declaration.Identifier,
            MethodDeclarationSyntax declaration => declaration.Identifier,
            LocalFunctionStatementSyntax declaration => declaration.Identifier,
            ConstructorDeclarationSyntax declaration => declaration.Identifier,
            DestructorDeclarationSyntax declaration => declaration.Identifier,
            PropertyDeclarationSyntax declaration => declaration.Identifier,
            EventDeclarationSyntax declaration => declaration.Identifier,
            EnumMemberDeclarationSyntax declaration => declaration.Identifier,
            VariableDeclaratorSyntax declaration => declaration.Identifier,
            ParameterSyntax declaration => declaration.Identifier,
            TypeParameterSyntax declaration => declaration.Identifier,
            TupleElementSyntax declaration => declaration.Identifier,
            SingleVariableDesignationSyntax declaration => declaration.Identifier,
            ForEachStatementSyntax declaration => declaration.Identifier,
            CatchDeclarationSyntax declaration => declaration.Identifier,
            FromClauseSyntax declaration => declaration.Identifier,
            JoinClauseSyntax declaration => declaration.Identifier,
            JoinIntoClauseSyntax declaration => declaration.Identifier,
            LetClauseSyntax declaration => declaration.Identifier,
            QueryContinuationSyntax declaration => declaration.Identifier,
            LabeledStatementSyntax declaration => declaration.Identifier,
            ExternAliasDirectiveSyntax declaration => declaration.Identifier,
            DefineDirectiveTriviaSyntax declaration => declaration.Name,
            UsingDirectiveSyntax { Alias: not null } declaration => declaration.Alias.Name.Identifier,
            AnonymousObjectMemberDeclaratorSyntax { NameEquals: not null } declaration => declaration.NameEquals.Name.Identifier,
            _ => default
        };
        if (identifier.RawKind != 0) yield return identifier;
        if (node is BaseNamespaceDeclarationSyntax space)
            foreach (var token in space.Name.DescendantTokens().Where(token => token.IsKind(SyntaxKind.IdentifierToken)))
                yield return token;
    }

    private static void Inspect(string path, int line, string kind, string value, List<string> errors)
    {
        foreach (var term in Terms.Where(term => value.Contains(term, StringComparison.OrdinalIgnoreCase)))
            errors.Add($"{path}:{line}: {kind} contains '{term}'; name and explain the responsibility (STD-CODE).");
    }

    private static string Run(string root, string executable, string[] arguments, string? input = null)
    {
        var info = new ProcessStartInfo(executable)
        {
            WorkingDirectory = root, RedirectStandardInput = input is not null,
            RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, CreateNoWindow = true
        };
        foreach (var argument in arguments) info.ArgumentList.Add(argument);
        using var process = Process.Start(info) ?? throw new InvalidOperationException("Could not start source parser: " + executable);
        if (input is not null) { process.StandardInput.Write(input); process.StandardInput.Close(); }
        var errors = process.StandardError.ReadToEndAsync();
        var output = process.StandardOutput.ReadToEnd();
        process.WaitForExit();
        var error = errors.GetAwaiter().GetResult();
        if (process.ExitCode != 0) throw new InvalidOperationException($"Source parser failed ({executable}): {error}\n{output}");
        return output;
    }
}
