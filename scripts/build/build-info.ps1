param([Parameter(Mandatory)][string]$Root,[Parameter(Mandatory)][string]$Output,[string]$Configuration='Debug')
$ErrorActionPreference='Stop'
. (Join-Path $Root 'scripts/lib/common.ps1')
$rootPath=[IO.Path]::GetFullPath($Root)
$version=(Get-Content -LiteralPath (Join-Path $rootPath 'version.txt') -Raw -Encoding UTF8).Trim()
$commit=(Invoke-UESTCGit $rootPath @('rev-parse','--short=12','HEAD')).StdOut.Trim()
if(@(Get-UESTCGitLines $rootPath @('status','--porcelain')).Count -gt 0){$commit+="-dirty"}
$commitFile=Join-Path $rootPath 'game/data/build-commit.txt'
$commitSource="$commit`n"
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($commitFile)) | Out-Null
if(-not(Test-Path -LiteralPath $commitFile) -or [IO.File]::ReadAllText($commitFile) -ne $commitSource){[IO.File]::WriteAllText($commitFile,$commitSource,[Text.UTF8Encoding]::new($false))}
$kind=if($Configuration -eq 'Debug'){'dev'}else{'export'}
$moduleProjects=@(Get-ChildItem -LiteralPath (Join-Path $rootPath 'game/gen') -Recurse -Filter *.csproj | Where-Object { $_.FullName -notmatch '(?i)[\\/](obj|bin|tests)[\\/]' -and $_.BaseName -notmatch 'Tests' })
$moduleProjects+=Get-Item -LiteralPath (Join-Path $rootPath 'pipeline/map/Campus.Pipeline.Map.csproj')
$moduleNames=[string[]]@($moduleProjects | ForEach-Object BaseName)
[Array]::Sort($moduleNames,[StringComparer]::Ordinal)
$names=@($moduleNames | ForEach-Object {'"'+$_+'"'}) -join ','
$source=@"
// <auto-generated />
namespace Campus.Kernel.Registry;
internal static class BuildInfo {
 public const string Version = "$version";
 public static string Commit => Godot.FileAccess.GetFileAsString("res://data/build-commit.txt").Trim();
 public static string Build => Version + "+" + Commit;
 public const string Kind = "$kind";
 public static readonly string[] ModuleAssemblies = [$names];
}
"@
$source=$source.Replace("`r`n","`n")
$destination=[IO.Path]::GetFullPath($Output)
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($destination)) | Out-Null
if(-not(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination) -ne $source){[IO.File]::WriteAllText($destination,$source,[Text.UTF8Encoding]::new($false))}
