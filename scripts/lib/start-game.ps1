# 正式启动的内部共用步骤：按已有构建与导入记录判鲜，在同一构建锁内更新并创建游戏进程。
# 用法：点引用 common.ps1 与本文件，再 Invoke-UESTCStartGame -Root <仓库> -Godot <引擎> [-BuildLease <已持有的锁>]；MSBuild 内部用 -BuildReceiptPhase 记录构建边界。
# 产出：output/start_game/；output/.locks/build.lock（按需构建与导入后启动游戏）。
param([ValidateSet('Begin', 'BeginRebuild', 'Complete')][string]$BuildReceiptPhase,
    [string]$BuildReceiptRoot, [string]$BuildReceiptProperties)
function Get-UESTCLaunchFiles {
    param([string]$Directory, [switch]$Import, [string]$BuildInputRoot)
    foreach ($entry in [IO.Directory]::EnumerateFileSystemEntries($Directory)) {
        $name = [IO.Path]::GetFileName($entry)
        if ([IO.Directory]::Exists($entry)) {
            if ($name.StartsWith('.') -or $name -in @('obj', 'bin', 'tests', 'testing')) { continue }
            if ($name -eq 'bake' -and (-not $BuildInputRoot -or $entry -eq (Join-Path $BuildInputRoot 'bake'))) { continue }
            if ($Import -and [IO.File]::Exists((Join-Path $entry '.gdignore'))) { continue }
            Get-UESTCLaunchFiles $entry -Import:$Import -BuildInputRoot $BuildInputRoot
        } else { [IO.FileInfo]::new($entry) }
    }
}

# CoreCompile is timestamp incremental; this one receipt records the successful
# build's full input bytes instead of treating a file or directory time as identity.
function Get-UESTCLaunchBuildInputs {
    param([string]$Root, [string[]]$GraphInputs)
    $Root = [IO.Path]::GetFullPath($Root).TrimEnd('\', '/')
    $inputs = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($path in $GraphInputs) {
        $full = [IO.Path]::GetFullPath($path)
        # The graph also returns generated Compile items, project assemblies and
        # CoreCompileInputs.cache. Those are outputs, not source identities.
        if ($full.StartsWith($Root + '\', [StringComparison]::OrdinalIgnoreCase) -and
            $full.Substring($Root.Length + 1) -match '(^|[\\/])(obj|bin|\.godot)([\\/]|$)|^(output|build)[\\/]') { continue }
        $null = $inputs.Add($full)
    }
    foreach ($name in @('global.json', 'scripts\gates\shader-whitelist.json', 'docs\ROUTES.json', 'version.txt',
        'Directory.Build.props', 'Directory.Build.targets', 'Directory.Packages.props', 'scripts\lib\start-game.ps1',
        'scripts\build\build-info.ps1', 'scripts\build\generate-style-shaders.py', 'game\project.godot',
        'game\style\palette\core.json', 'game\addons\build_import\plugin.cfg', 'game\addons\build_import\plugin.gd',
        'scripts\setup\install-test-runner.ps1')) { $null = $inputs.Add((Join-Path $Root $name)) }
    foreach ($path in @(Get-UESTCLaunchPackageInputs $Root)) { $null = $inputs.Add($path) }
    foreach ($name in @('NuGet.Config', 'nuget.config', '.editorconfig')) {
        $path = Join-Path $Root $name
        if ([IO.File]::Exists($path)) { $null = $inputs.Add($path) }
    }
    foreach ($file in Get-ChildItem -LiteralPath (Join-Path $Root 'scripts\gates\arch') -Filter 'BannedSymbols.*.txt' -File) {
        $null = $inputs.Add($file.FullName)
    }
    # Enumerate the current tree, not just the previous receipt, so globbed
    # sources and projects disappearing, appearing or being renamed change identity.
    foreach ($directory in @('game', 'scripts\build\fingerprints')) {
        $sourceRoot = Join-Path $Root $directory
        foreach ($file in @(Get-UESTCLaunchFiles $sourceRoot -BuildInputRoot $sourceRoot)) {
            if ($file.Extension -in @('.cs', '.csproj', '.props', '.targets', '.ruleset', '.glsl', '.glslinc', '.gdshaderinc') -or
                $file.Name -match '^(\.editorconfig|BannedSymbols.*\.txt|packages\.lock\.json|nuget\.config)$') {
                $null = $inputs.Add($file.FullName)
            }
        }
    }
    # These files are generated by the existing build targets; their generators
    # and configuration inputs above carry the identity, including on a clean build.
    foreach ($name in @('game\style\shaders\style_consts.gdshaderinc', 'game\style\outline\fog.glslinc',
        'game\gdunit4_testadapter_v5\GdUnit4TestRunnerScene.cs')) { $null = $inputs.Remove((Join-Path $Root $name)) }
    $paths = [string[]]@($inputs)
    [Array]::Sort($paths, [StringComparer]::Ordinal)
    return $paths
}

# Read restore's package/configuration paths, never hash its generated metadata.
function Get-UESTCLaunchPackageInputs {
    param([string]$Root)
    $packages = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($relative in @('game\obj\Campus\Campus.csproj.nuget.dgspec.json',
        'scripts\build\fingerprints\obj\Campus.CodeFingerprints\Campus.CodeFingerprints.csproj.nuget.dgspec.json')) {
        $graph = [IO.File]::ReadAllText((Join-Path $Root $relative)) | ConvertFrom-Json
        foreach ($project in $graph.projects.PSObject.Properties) {
            $project.Name
            foreach ($config in $project.Value.restore.configFilePaths) { $config }
            $assetsPath = Join-Path $project.Value.restore.outputPath 'project.assets.json'
            $assets = [IO.File]::ReadAllText($assetsPath) | ConvertFrom-Json
            foreach ($library in $assets.libraries.PSObject.Properties) {
                if ($library.Value.type -ne 'package') { continue }
                $folders = @($assets.packageFolders.PSObject.Properties.Name)
                $package = Join-Path $folders[0] $library.Value.path
                foreach ($folder in $folders) {
                    $candidate = Join-Path $folder $library.Value.path
                    if ([IO.Directory]::Exists($candidate)) { $package = $candidate; break }
                }
                if ($packages.Add($package)) {
                    foreach ($file in $library.Value.files) {
                        if ($file -match '\.(dll|props|targets)$') { Join-Path $package $file }
                    }
                }
            }
        }
    }
}
function Get-UESTCLaunchBuildIdentity {
    param([string]$Root, [string[]]$GraphInputs, [string]$Properties)
    $sha = [Security.Cryptography.SHA256]::Create()
    $buffer = [IO.MemoryStream]::new()
    $writer = [IO.BinaryWriter]::new($buffer, [Text.Encoding]::UTF8, $true)
    try {
        $writer.Write('campus-launch-build-v1')
        $writer.Write($Properties)
        foreach ($path in @(Get-UESTCLaunchBuildInputs $Root $GraphInputs)) {
            $writer.Write($path)
            $stream = [IO.File]::OpenRead($path)
            try { $writer.Write($sha.ComputeHash($stream)) } finally { $stream.Dispose() }
        }
        $writer.Flush()
        $buffer.Position = 0
        return [BitConverter]::ToString($sha.ComputeHash($buffer)).Replace('-', '').ToLowerInvariant()
    } finally { $writer.Dispose(); $buffer.Dispose(); $sha.Dispose() }
}

function Get-UESTCLaunchBuildGraph {
    param([string]$Root, [string]$Properties)
    foreach ($project in @('game\Campus.csproj', 'scripts\build\fingerprints\Campus.CodeFingerprints.csproj')) {
        # The existing target owns Compile/reference selection. Query only: no
        # Build/CoreCompile, project-reference build or success-receipt recursion.
        $result = Invoke-UESTCProcess 'dotnet' @('msbuild', (Join-Path $Root $project),
            '-target:GetCampusCodeFingerprintInputs', '-getTargetResult:GetCampusCodeFingerprintInputs',
            "-property:$Properties;DesignTimeBuild=true;BuildProjectReferences=false", '-verbosity:quiet', '-nologo') $Root
        $graph = $result.StdOut | ConvertFrom-Json
        foreach ($item in $graph.TargetResults.GetCampusCodeFingerprintInputs.Items) { $item.Identity }
    }
}

function Update-UESTCLaunchBuildReceipt {
    param([string]$Root, [string]$Phase, [string]$Properties)
    $Root = [IO.Path]::GetFullPath($Root).TrimEnd('\', '/')
    $path = Join-Path $Root 'output\start_game\build.succeeded'
    if ($Phase -in @('Begin', 'BeginRebuild')) {
        # Invalidate before any output can be overwritten, including if querying
        # inputs or the subsequent build fails. Pending is never a fresh receipt.
        $previous = $null
        if ([IO.File]::Exists($path)) {
            $text = [IO.File]::ReadAllText($path)
            if (-not [string]::IsNullOrWhiteSpace($text)) { $previous = $text | ConvertFrom-Json }
            [IO.File]::Delete($path)
        }
        $graphInputs = @(Get-UESTCLaunchBuildGraph $Root $Properties)
        $identity = Get-UESTCLaunchBuildIdentity $Root $graphInputs $Properties
        $verified = $previous -and $previous.format -eq 1 -and $previous.status -eq 'succeeded' -and
            $previous.properties -eq $Properties -and $previous.identity -eq $identity
        $receipt = [ordered]@{ format=1; status='building'; properties=$Properties; identity=$identity;
            graphInputs=$graphInputs; rebuild=($Phase -eq 'BeginRebuild'); verified=[bool]$verified }
    } else {
        $before = [IO.File]::ReadAllText($path) | ConvertFrom-Json
        if ($before.format -ne 1 -or $before.status -ne 'building' -or $before.properties -ne $Properties) {
            throw 'Build input receipt was not started by this build.'
        }
        $graphInputs = @(Get-UESTCLaunchBuildGraph $Root $Properties)
        $identity = Get-UESTCLaunchBuildIdentity $Root $graphInputs $Properties
        if ($identity -ne $before.identity) { throw 'Build inputs changed during the build; rebuild before launching.' }
        if (-not $before.rebuild -and -not $before.verified) {
            Write-Warning 'Build inputs have no matching verified receipt; use dotnet build -t:Rebuild before launching.'
            return
        }
        $receipt = [ordered]@{ format=1; status='succeeded'; properties=$Properties; identity=$identity; graphInputs=$graphInputs }
    }
    $null = [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path))
    $staging = $path + '.tmp'
    try {
        [IO.File]::WriteAllText($staging, ($receipt | ConvertTo-Json -Depth 5), [Text.UTF8Encoding]::new($false))
        if ([IO.File]::Exists($path)) { [IO.File]::Replace($staging, $path, [NullString]::Value) }
        else { [IO.File]::Move($staging, $path) }
    } finally { if ([IO.File]::Exists($staging)) { [IO.File]::Delete($staging) } }
}

function Test-UESTCLaunchBuild {
    param([string]$Root)
    $Root = [IO.Path]::GetFullPath($Root).TrimEnd('\', '/')
    $game = Join-Path $Root 'game'
    $output = Join-Path $game '.godot\mono\temp\bin\Debug'
    $graphPath = Join-Path $game 'obj\Campus\Campus.csproj.nuget.dgspec.json'
    $stamp = Join-Path $Root 'output\start_game\build.succeeded'
    if (-not [IO.File]::Exists((Join-Path $output 'Campus.dll')) -or -not [IO.File]::Exists($graphPath) -or
        -not [IO.File]::Exists((Join-Path $game 'data\build-code-fingerprints.json')) -or -not [IO.File]::Exists($stamp)) { return $false }
    # Empty legacy stamps and interrupted/failed builds require one real build.
    $text = [IO.File]::ReadAllText($stamp)
    if ([string]::IsNullOrWhiteSpace($text)) { return $false }
    $receipt = $text | ConvertFrom-Json
    if ($receipt.format -ne 1 -or $receipt.status -ne 'succeeded' -or
        $receipt.properties -notmatch '(^|;)Configuration=Debug(;|$)') { return $false }
    $toolGraph = Join-Path $Root 'scripts\build\fingerprints\obj\Campus.CodeFingerprints\Campus.CodeFingerprints.csproj.nuget.dgspec.json'
    if (-not [IO.File]::Exists($toolGraph)) { return $false }
    foreach ($restoreGraphPath in @($graphPath, $toolGraph)) {
        $restoreGraph = [IO.File]::ReadAllText($restoreGraphPath) | ConvertFrom-Json
        foreach ($project in $restoreGraph.projects.PSObject.Properties) {
            if (-not [IO.File]::Exists((Join-Path $project.Value.restore.outputPath 'project.assets.json'))) { return $false }
        }
    }
    $graph = [IO.File]::ReadAllText($graphPath) | ConvertFrom-Json
    foreach ($project in $graph.projects.PSObject.Properties) {
        $name = [IO.Path]::GetFileNameWithoutExtension($project.Name)
        if (-not [IO.File]::Exists($project.Name) -or -not [IO.File]::Exists((Join-Path $output "$name.dll"))) { return $false }
        if (-not [IO.File]::Exists((Join-Path $project.Value.restore.outputPath 'project.assets.json'))) { return $false }
        $intermediate = if ($name -eq 'Campus') { Join-Path $game '.godot\mono\temp\obj\Debug' }
            else { Join-Path $project.Value.restore.outputPath 'Debug\net10.0' }
        $list = Join-Path $intermediate "$name.csproj.FileListAbsolute.txt"
        if (-not [IO.File]::Exists($list)) { return $false }
        foreach ($written in [IO.File]::ReadLines($list)) {
            if ($written.StartsWith($Root + '\', [StringComparison]::OrdinalIgnoreCase) -and -not [IO.File]::Exists($written)) { return $false }
        }
    }
    foreach ($input in @(Get-UESTCLaunchBuildInputs $Root @($receipt.graphInputs))) {
        if (-not [IO.File]::Exists($input)) { return $false }
    }
    return (Get-UESTCLaunchBuildIdentity $Root @($receipt.graphInputs) $receipt.properties) -eq $receipt.identity
}
function Test-UESTCLaunchImport {
    param([string]$Root, [string]$Godot)
    $game = Join-Path $Root 'game'
    $cache = Join-Path $game '.godot\editor\filesystem_cache10'
    if (-not [IO.File]::Exists($cache) -or -not [IO.File]::Exists((Join-Path $game '.godot\uid_cache.bin'))) { return $false }
    if ([IO.File]::GetLastWriteTimeUtc((Join-Path $game 'project.godot')) -gt [IO.File]::GetLastWriteTimeUtc($cache) -or
        [IO.File]::GetLastWriteTimeUtc($Godot) -gt [IO.File]::GetLastWriteTimeUtc($cache)) { return $false }
    $records = @{}
    $directory = ''
    foreach ($line in [IO.File]::ReadLines($cache)) {
        $parts = $line -split '::'
        if ($line.StartsWith('::res://')) { $directory = $parts[1].Substring(6); continue }
        if ($parts.Count -ge 6) { $records[$directory + $parts[0]] = $parts }
    }
    foreach ($relative in $records.Keys) {
        if ($records[$relative][4] -ne '0' -and -not [IO.File]::Exists((Join-Path $game $relative))) { return $false }
    }
    # The filesystem cache records both source and .import mtimes, as integer
    # Unix seconds. Read that Godot metadata instead of hashing every asset.
    $importedAt = [IO.File]::GetLastWriteTimeUtc($cache)
    $epoch = [DateTime]::SpecifyKind([DateTime]'1970-01-01', [DateTimeKind]::Utc)
    foreach ($file in @(Get-UESTCLaunchFiles $game -Import)) {
        if ($file.Extension -eq '.import') {
            if (-not [IO.File]::Exists($file.FullName.Substring(0, $file.FullName.Length - 7))) { return $false }
            continue
        }
        # Includes have no .import sidecar. The existing scan timestamp is only
        # a cheap trigger; dependency selection belongs to the editor import step.
        if ($file.Extension -in @('.glslinc', '.gdshaderinc') -and $file.LastWriteTimeUtc -gt $importedAt) { return $false }
        $relative = $file.FullName.Substring($game.Length + 1).Replace('\', '/')
        $sidecar = $file.FullName + '.import'
        if (-not [IO.File]::Exists($sidecar)) {
            # New resources are absent from the existing scan. Code, raw data
            # and directly loaded shaders/scenes do not require an import pass.
            if ($file.Extension -match '^\.(csv|svg|png|jpe?g|webp|bmp|tga|hdr|exr|ktx|dds|wav|ogg|mp3|ttf|otf|woff2?|glsl|gltf|glb|fbx|blend|obj)$') { return $false }
            continue
        }
        if (-not $records.ContainsKey($relative)) { return $false }
        $record = $records[$relative]
        if ($record[5] -ne '1' -or [long][Math]::Floor(($file.LastWriteTimeUtc - $epoch).TotalSeconds) -ne [long]$record[3] -or
            [long][Math]::Floor(([IO.File]::GetLastWriteTimeUtc($sidecar) - $epoch).TotalSeconds) -ne [long]$record[4]) { return $false }
        $text = [IO.File]::ReadAllText($sidecar)
        foreach ($match in [regex]::Matches($text, '"res://([^"\r\n]+)"')) {
            if (-not [IO.File]::Exists((Join-Path $game $match.Groups[1].Value))) { return $false }
        }
    }
    return $true
}

# DECISION-256: keep the script-entry and engine clocks separate; external lock wait is never fabricated.
function New-UESTCLaunchTiming {
    param([DateTime]$ScriptEnteredUtc = [DateTime]::UtcNow,
        [long]$ScriptEnteredTimestamp = [Diagnostics.Stopwatch]::GetTimestamp())
    return [ordered]@{ scriptEnteredUtc=$ScriptEnteredUtc.ToString('O'); scriptEnteredTimestamp=$ScriptEnteredTimestamp;
        stopwatchFrequency=[Diagnostics.Stopwatch]::Frequency; lockWaitStatus='NOT_MEASURED';
        lockRequestedTimestamp=$null; lockAcquiredTimestamp=$null;
        freshnessStartedTimestamp=$null; freshnessCompletedTimestamp=$null;
        buildInvoked=$null; importInvoked=$null; engineLaunchRequestedTimestamp=$null;
        engineStartUtc=$null; status='INITIALIZING' }
}

function Initialize-UESTCLaunch {
    param([Parameter(Mandatory)][string]$Root, [Parameter(Mandatory)][string]$Godot,
        [Parameter(Mandatory)][IO.FileStream]$BuildLease, [Collections.IDictionary]$Timing = $null, [switch]$RequireFresh)
    if ($Timing) { $Timing['freshnessStartedTimestamp'] = [Diagnostics.Stopwatch]::GetTimestamp() }
    $out = Join-Path $Root 'output\start_game'
    $null = [IO.Directory]::CreateDirectory($out)
    $built = -not (Test-UESTCLaunchBuild $Root)
    if ($Timing) { $Timing['buildInvoked'] = $false; $Timing['importInvoked'] = $false }
    if ($built -and $RequireFresh) { throw 'Existing build is stale; prepare it before the measurement.' }
    if ($built) {
        if ($Timing) { $Timing['buildInvoked'] = $true }
        Write-Host '构建有变化，编译中……'
        Invoke-UESTCProcess 'dotnet' @('build', "$Root\game\Campus.csproj", '-t:Rebuild', '-c', 'Debug', '-v', 'q') $Root (Join-Path $out 'build.log') | Out-Null
    }
    # A build can change generated includes without changing an RD main source.
    $imported = $built -or -not (Test-UESTCLaunchImport $Root $Godot)
    if ($imported -and $RequireFresh) { throw 'Existing import is stale; prepare it before the measurement.' }
    if ($imported) {
        if ($Timing) { $Timing['importInvoked'] = $true }
        Write-Host '导入资源有变化，导入中……'
        $import = Invoke-UESTCProcess $Godot @('--headless', '--editor', '--path', "$Root\game", '--', '--build-import') $Root (Join-Path $out 'import.log') -TimeoutSeconds 600
        Assert-UESTCCleanGodotLog $import
    }
    if ($Timing) { $Timing['freshnessCompletedTimestamp'] = [Diagnostics.Stopwatch]::GetTimestamp() }
}

function Invoke-UESTCStartGame {
    param([Parameter(Mandatory)][string]$Root, [Parameter(Mandatory)][string]$Godot,
        [string[]]$GameArgs = @(), [IO.FileStream]$BuildLease = $null,
        [DateTime]$ScriptEnteredUtc = [DateTime]::UtcNow,
        [long]$ScriptEnteredTimestamp = [Diagnostics.Stopwatch]::GetTimestamp())
    $Root = [IO.Path]::GetFullPath($Root).TrimEnd('\', '/')
    $timing = New-UESTCLaunchTiming -ScriptEnteredUtc $ScriptEnteredUtc -ScriptEnteredTimestamp $ScriptEnteredTimestamp
    $lease = $null
    try {
        if (-not $BuildLease) {
            $timing['lockRequestedTimestamp'] = [Diagnostics.Stopwatch]::GetTimestamp()
            $lease = Enter-UESTCBuildLock (Get-UESTCLayout $Root).Locks
            $timing['lockAcquiredTimestamp'] = [Diagnostics.Stopwatch]::GetTimestamp()
            $timing['lockWaitStatus'] = 'MEASURED_IN_TOTAL'
        } else { $timing['lockWaitStatus'] = 'ALREADY_HELD; external wait NOT_MEASURED' }
        $heldLease = if ($BuildLease) { $BuildLease } else { $lease }
        Initialize-UESTCLaunch -Root $Root -Godot $Godot -BuildLease $heldLease -Timing $timing
        $window = $Godot -replace '_console\.exe$', '.exe'
        if (-not [IO.File]::Exists($window)) { $window = $Godot }
        $arguments = @('--path', "$Root\game")
        if ($GameArgs.Count) { $arguments += @('--') + $GameArgs }
        $commandLine = ($arguments | ForEach-Object { ConvertTo-UESTCProcessArgument $_ }) -join ' '
        $timing['engineLaunchRequestedTimestamp'] = [Diagnostics.Stopwatch]::GetTimestamp()
        $process = Start-Process -FilePath $window -ArgumentList $commandLine -WorkingDirectory $Root -WindowStyle Normal -PassThru
        $timing['engineStartUtc'] = $process.StartTime.ToUniversalTime().ToString('O')
        $timing['gamePid'] = $process.Id
        $timing['menuRequested'] = -not ($GameArgs -contains '--title=0')
        $timing['status'] = 'ENGINE_STARTED'
        return $process
    } catch { $timing['status'] = 'FAILED'; throw }
    finally {
        try {
            $out = Join-Path $Root 'output\start_game'
            $null = [IO.Directory]::CreateDirectory($out)
            $timing | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $out 'launch.json') -Encoding UTF8
        } finally { Exit-UESTCBuildLock $lease }
    }
}

if ($BuildReceiptPhase) {
    $ErrorActionPreference = 'Stop'
    . (Join-Path $PSScriptRoot 'common.ps1')
    Update-UESTCLaunchBuildReceipt -Root $BuildReceiptRoot -Phase $BuildReceiptPhase -Properties $BuildReceiptProperties
}
