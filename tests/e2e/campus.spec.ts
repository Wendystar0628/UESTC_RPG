import { test, expect } from '@playwright/test';

test('desktop: real scene, search, filter reveal, camera jump, drag and layers', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.scene-canvas')).toHaveAttribute('data-textures-ready', 'true');
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-target', /\d/);
  await expect(page.locator('.map-marker').first()).toBeVisible();
  await page.screenshot({ path: 'test-results/overview.png' });
  const search = page.getByRole('combobox');
  await search.fill('图书馆');
  const libraryResult = page.locator('.result-main[title="图书馆 · 图书阅览"]');
  await expect(libraryResult).toBeVisible();
  const homeTarget = await page.locator('.map-view').getAttribute('data-camera-target');
  await libraryResult.click();
  await expect(page.locator('.entity-details h2')).toHaveText('图书馆');
  await expect(page.locator('.map-view')).not.toHaveAttribute('data-camera-target', homeTarget!);
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-status', 'idle');
  await expect(page.locator('.map-marker.selected')).toBeVisible();
  await page.screenshot({ path: 'test-results/library.png' });
  await page.getByRole('button', { name: '关闭地点详情' }).click();
  await page.getByRole('button', { name: '筛选餐饮', exact: true }).click();
  await libraryResult.click();
  await expect(page.locator('.inline-notice')).toContainText('临时显示');
  await page.getByRole('button', { name: '关闭地点详情' }).click();
  await expect(page.getByRole('button', { name: '筛选餐饮', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: '当前分类', exact: true }).click();
  await expect(page.locator('.result-row')).toHaveCount(0);
  await page.getByRole('button', { name: '改为全校搜索' }).click();
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  await libraryResult.click();
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-status', 'idle');
  const focusTarget = await page.locator('.map-view').getAttribute('data-camera-target');
  const canvas = await page.locator('canvas').boundingBox();
  if (!canvas) throw new Error('No canvas');
  await page.mouse.move(canvas.x + 90, canvas.y + 180);
  await page.mouse.down();
  await page.mouse.move(canvas.x + 170, canvas.y + 210, { steps: 12 });
  await page.mouse.up();
  await expect(page.locator('.entity-details h2')).toHaveText('图书馆');
  await expect(page.locator('.map-view')).not.toHaveAttribute('data-camera-target', focusTarget!);
  await page.getByRole('button', { name: '跳转到此处', exact: true }).click();
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-status', 'idle');
  await page.getByRole('button', { name: '返回全校总览' }).click();
  await expect(page.locator('.entity-details')).toHaveCount(0);
  await page.getByRole('button', { name: '图层设置' }).click();
  await page.getByRole('checkbox', { name: '名称标注', exact: true }).uncheck();
  await expect(page.locator('.map-marker .marker-name')).toHaveCount(0);
  await page.getByRole('checkbox', { name: '名称标注', exact: true }).check();
  await page.getByRole('button', { name: '关闭图层设置' }).click();
  await expect(page.locator('canvas')).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile: search drawer, keyboard selection and visible target', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('.scene-canvas')).toHaveAttribute('data-textures-ready', 'true');
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-target', /\d/);
  const homeTarget = await page.locator('.map-view').getAttribute('data-camera-target');
  await page.getByRole('button', { name: '搜索校园', exact: true }).click();
  await page.getByRole('combobox').fill('图书馆');
  await page.getByRole('combobox').press('Enter');
  await expect(page.locator('.entity-details h2')).toHaveText('图书馆');
  await expect(page.locator('.explorer')).not.toHaveClass(/open/);
  await expect(page.locator('.map-view')).not.toHaveAttribute('data-camera-target', homeTarget!);
  await expect(page.locator('.map-view')).toHaveAttribute('data-camera-status', 'idle');
  await expect(page.locator('.map-marker.selected')).toBeVisible();
  const marker = await page.locator('.map-marker.selected').boundingBox();
  const details = await page.locator('.entity-details').boundingBox();
  expect(marker!.y + marker!.height).toBeLessThan(details!.y);
  await page.screenshot({ path: 'test-results/mobile.png' });
  await page.getByRole('button', { name: '关闭地点详情' }).click();
  await page.getByRole('button', { name: '操作帮助' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.setViewportSize({ width: 320, height: 844 });
  const labels = page.getByRole('button', { name: '建筑标签', exact: true });
  await expect(labels).toBeVisible();
  await labels.click();
  await expect(page.locator('.map-marker')).toHaveCount(0);
  await labels.click();
  await expect(page.locator('.map-marker').first()).toBeVisible();
  const button = (await labels.boundingBox())!;
  expect(button.x + button.width).toBeLessThanOrEqual(320);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320);
  await page.screenshot({ path: 'test-results/labels-mobile.png' });
});
